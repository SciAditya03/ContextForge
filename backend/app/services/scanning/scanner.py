"""Layer 0: repository discovery."""

from __future__ import annotations

import hashlib
import os
import re
from collections import defaultdict
from collections.abc import Callable
from pathlib import Path

from app.schemas.facts import DirectoryNode, FileCategory, FileRecord, RepositoryOverview
from app.services.extraction.safe_zip import matches_exclusion
from app.services.scanning import languages as L
from app.services.scanning.classifier import classify, detect_entry_point, detect_language

TEXT_SNIFF = 8192
_GENERATED_PATH = re.compile(r"(\.gen\.[a-z]+$|_pb2(_grpc)?\.py$|\.pb\.go$|\.g\.dart$|\.freezed\.dart$|(^|/)(generated|__generated__|gen)/|\.generated\.[a-z]+$)", re.I)
_GENERATED_HEAD = re.compile(r"(auto-?generated|@generated|do not edit|code generated by|this file was generated|generated by the protocol buffer)", re.I)


def is_generated(path: str, head: str) -> bool:
    return bool(_GENERATED_PATH.search(path) or _GENERATED_HEAD.search(head[:600]))


def is_binary_bytes(data: bytes) -> bool:
    if not data:
        return False
    if b"\x00" in data:
        return True
    try:
        data.decode("utf-8")
        return False
    except UnicodeDecodeError as exc:
        # tolerate a truncated multibyte sequence at the end of the sniff window
        if exc.start >= len(data) - 4:
            return False
    nontext = sum(1 for b in data if b < 9 or (13 < b < 32))
    return nontext / len(data) > 0.1


def read_text(path: Path, max_bytes: int | None = None) -> str:
    with open(path, "rb") as fh:
        data = fh.read() if max_bytes is None else fh.read(max_bytes)
    return data.decode("utf-8", errors="replace")


def count_lines(text: str, language: str | None) -> tuple[int, int]:
    lines = text.splitlines()
    prefixes = L.LINE_COMMENT.get(language or "", L.DEFAULT_LINE_COMMENT)
    code = 0
    in_block = False
    for raw in lines:
        s = raw.strip()
        if not s:
            continue
        if in_block:
            if "*/" in s:
                in_block = False
            continue
        if s.startswith("/*") and language not in {"Python", "Shell", "YAML"}:
            if "*/" not in s:
                in_block = True
            continue
        if s.startswith(prefixes):
            continue
        code += 1
    return len(lines), code


def build_tree(root_name: str, paths: list[str]) -> DirectoryNode:
    root = DirectoryNode(name=root_name, path="")
    index: dict[str, DirectoryNode] = {"": root}
    for p in sorted(paths):
        parts = p.split("/")
        cur = ""
        for part in parts[:-1]:
            nxt = f"{cur}/{part}" if cur else part
            if nxt not in index:
                node = DirectoryNode(name=part, path=nxt)
                index[cur].children.append(node)
                index[nxt] = node
            cur = nxt
        index[cur].files += 1
    return root


def scan_repository(
    root: Path,
    root_name: str,
    exclusions: list[str],
    pre_excluded: list[tuple[str, str]] | None = None,
    pre_skipped: list[tuple[str, str]] | None = None,
    progress: Callable[[int, int], None] | None = None,
) -> tuple[RepositoryOverview, list[FileRecord], DirectoryNode]:
    all_paths: list[str] = []
    for dirpath, dirnames, filenames in os.walk(root, followlinks=False):
        rel_dir = os.path.relpath(dirpath, root)
        rel_dir = "" if rel_dir == "." else rel_dir.replace(os.sep, "/")
        dirnames.sort()
        for fn in sorted(filenames):
            full = Path(dirpath) / fn
            if full.is_symlink():
                continue
            all_paths.append(f"{rel_dir}/{fn}" if rel_dir else fn)

    records: list[FileRecord] = []
    total = len(all_paths)
    for i, rel in enumerate(all_paths):
        full = root / rel
        size = full.stat().st_size
        lang = detect_language(rel)
        rec = FileRecord(path=rel, size=size, language=lang)
        pat = matches_exclusion(rel, exclusions)
        if pat:
            rec.status, rec.status_reason = "excluded", f"excluded by pattern '{pat}'"
            rec.category = classify(rel, lang)
            records.append(rec)
            continue
        with open(full, "rb") as fh:
            head_bytes = fh.read(TEXT_SNIFF)
        if is_binary_bytes(head_bytes) or classify(rel, lang) in (FileCategory.BINARY, FileCategory.ASSET):
            rec.is_binary = is_binary_bytes(head_bytes)
            rec.category = classify(rel, lang)
            if rec.category not in (FileCategory.ASSET,):
                rec.category = FileCategory.BINARY if rec.is_binary else rec.category
            rec.sha256 = hashlib.sha256(full.read_bytes()).hexdigest()
            rec.status, rec.status_reason = "skipped", "binary or asset file (not analysed)"
            records.append(rec)
            continue
        data = full.read_bytes()
        rec.sha256 = hashlib.sha256(data).hexdigest()
        text = data.decode("utf-8", errors="replace")
        rec.lines, rec.code_lines = count_lines(text, lang)
        rec.category = classify(rel, lang)
        rec.generated = is_generated(rel, text)
        reason = detect_entry_point(rel, text[:20000])
        if reason and rec.category in (FileCategory.SOURCE,):
            rec.is_entry_point, rec.entry_point_reason = True, reason
        records.append(rec)
        if progress and (i % 50 == 0 or i == total - 1):
            progress(i + 1, total)

    for rel, reason in pre_excluded or []:
        records.append(FileRecord(path=rel, size=0, language=detect_language(rel), status="excluded", status_reason=reason, category=classify(rel, detect_language(rel))))
    for rel, reason in pre_skipped or []:
        records.append(FileRecord(path=rel, size=0, language=detect_language(rel), status="skipped", status_reason=reason, category=classify(rel, detect_language(rel))))

    included = [r for r in records if r.status == "included"]
    langs: dict[str, dict[str, int]] = defaultdict(lambda: {"files": 0, "lines": 0, "code_lines": 0, "bytes": 0})
    cats: dict[str, int] = defaultdict(int)
    for r in included:
        cats[r.category.value] += 1
        if r.language:
            d = langs[r.language]
            d["files"] += 1
            d["lines"] += r.lines
            d["code_lines"] += r.code_lines
            d["bytes"] += r.size

    def paths_of(*cs: FileCategory) -> list[str]:
        return [r.path for r in included if r.category in cs]

    manifests = paths_of(FileCategory.MANIFEST)
    subprojects = sorted({m.rsplit("/", 1)[0] if "/" in m else "." for m in manifests})
    overview = RepositoryOverview(
        root_name=root_name,
        total_files=len(records),
        included_files=len(included),
        excluded_files=sum(1 for r in records if r.status == "excluded"),
        source_files=sum(1 for r in included if r.category == FileCategory.SOURCE),
        test_files=sum(1 for r in included if r.category == FileCategory.TEST),
        total_lines=sum(r.lines for r in included),
        code_lines=sum(r.code_lines for r in included if r.language in L.CODE_LANGUAGES),
        total_bytes=sum(r.size for r in records),
        languages=dict(sorted(langs.items(), key=lambda kv: -kv[1]["code_lines"])),
        categories=dict(cats),
        entry_points=[r.path for r in included if r.is_entry_point],
        config_files=paths_of(FileCategory.CONFIG),
        docs_files=paths_of(FileCategory.DOCS),
        test_paths=paths_of(FileCategory.TEST),
        build_files=paths_of(FileCategory.BUILD),
        env_templates=paths_of(FileCategory.ENV_TEMPLATE),
        manifests=manifests,
        deploy_files=paths_of(FileCategory.DEPLOY),
        subprojects=subprojects,
    )
    tree = build_tree(root_name, [r.path for r in records if r.status != "excluded"])
    return overview, records, tree
