def _rec(p: str) -> FileRecord:
    return FileRecord(path=p, size=1, language="Python")


def test_pep758_unparenthesised_except_is_parsed():
    src = "try:\n    x()\nexcept ValueError, KeyError:\n    pass\nexcept* OSError, RuntimeError as e:\n    pass\n"
    assert compat_source(src) is not None and "except (ValueError, KeyError):" in compat_source(src)
    r = parse_python("deps.py", "import jwt\n" + src.replace("except*", "except"))
    assert r.module.parse_ok and "PEP 758" in (r.module.parse_error or "")


def test_fastapi_annotated_dependencies_and_constant_prefixes():
    config = parse_python("app/core/config.py", "class Settings:\n    API_V1_STR: str = '/api/v1'\nsettings = Settings()\n")
    deps = parse_python("app/api/deps.py", "from typing import Annotated\nfrom fastapi import Depends\n"
                        "SessionDep = Annotated[Session, Depends(get_db)]\nCurrentUser = Annotated[User, Depends(get_current_user)]\n")
    items = parse_python("app/api/routes/items.py", "from fastapi import APIRouter\nfrom app.api.deps import CurrentUser, SessionDep\n"
                         "router = APIRouter(prefix='/items')\n@router.post('/')\ndef create(session: SessionDep, current_user: CurrentUser, item_in: ItemCreate):\n    pass\n")
    api = parse_python("app/api/main.py", "from fastapi import APIRouter\nfrom app.api.routes import items\napi_router = APIRouter()\napi_router.include_router(items.router)\n")
    main = parse_python("app/main.py", "from fastapi import FastAPI\nfrom app.api.main import api_router\nfrom app.core.config import settings\n"
                        "app = FastAPI()\napp.include_router(api_router, prefix=settings.API_V1_STR)\n")
    results = [config, deps, items, api, main]
    files = [_rec(r.module.path) for r in results] + [_rec("app/api/routes/__init__.py"), _rec("app/api/__init__.py"), _rec("app/__init__.py")]
    routes = resolve_routes(results, ImportResolver(files, []))
    assert [(r.method, r.path) for r in routes] == [("POST", "/api/v1/items/")]
    rt = routes[0]
    assert rt.auth == ["get_current_user"] and "get_db" in rt.calls and rt.body_model == "ItemCreate"
    calls = parse_python("tests/test_items.py", "def test_it(client):\n    client.post(f'{settings.API_V1_STR}/items/', json={})\n").client_calls
    assert match_client_calls(calls, routes, project_constants(results))[0].matched_route == "POST /api/v1/items/"


def test_sqlmodel_inherited_fields_relationship_targets_and_default_table():
    src = (
        "from sqlmodel import Field, Relationship, SQLModel\n"
        "class UserBase(SQLModel):\n    email: str = Field(unique=True, index=True)\n    is_active: bool = True\n"
        "class User(UserBase, table=True):\n    id: int = Field(primary_key=True)\n    items: list['Item'] = Relationship(back_populates='owner')\n"
        "class Item(SQLModel, table=True):\n    id: int = Field(primary_key=True)\n    owner_id: int = Field(foreign_key='user.id')\n    owner: User | None = Relationship(back_populates='items')\n"
    )
    models = {m.name: m for m in parse_python("models.py", src).db_models}
    assert models["User"].table == "user" and [f.name for f in models["User"].fields] == ["email", "is_active", "id"]
    assert models["User"].relationships[0]["target"] == "Item" and models["Item"].relationships[0]["target"] == "User"
    assert next(f for f in models["Item"].fields if f.name == "owner_id").foreign_key == "user.id"


def test_generated_sdk_request_objects_are_client_calls():
    src = "export class ItemsService {\n  static read() {\n    return (options.client ?? client).get({ responseType: 'json', url: '/api/v1/items/', ...options });\n  }\n}\n" \
          "export const x = () => __request(OpenAPI, { method: 'DELETE', url: '/api/v1/items/{id}' });\n"
    calls = parse_typescript("src/client/sdk.gen.ts", src).client_calls
    assert [(c.method, c.url) for c in calls] == [("GET", "/api/v1/items/"), ("DELETE", "/api/v1/items/{id}")]


