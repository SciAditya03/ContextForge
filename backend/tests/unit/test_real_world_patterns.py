def test_env_file_with_placeholders_is_low_severity(tmp_path: Path):
    (tmp_path / ".env").write_text("SECRET_KEY=changethis\nPOSTGRES_PASSWORD=changethis\nDOMAIN=localhost\n")
    (tmp_path / "prod.env").write_text("x=1\n")
    files = [FileRecord(path=".env", size=10, language="Env", category=FileCategory.ENV_FILE)]
    findings, _ = scan_security(ScanContext(root=tmp_path, files=files, modules=[], routes=[], dependencies=[], env_vars=[], technologies=[]))
    env = next(f for f in findings if f.category == "secret-management")
    assert env.severity == "low" and "placeholders" in env.explanation
    (tmp_path / ".env").write_text("SECRET_KEY=Kq8vT2pLm9ZxW4rB7nC1\n")
    findings, _ = scan_security(ScanContext(root=tmp_path, files=files, modules=[], routes=[], dependencies=[], env_vars=[], technologies=[]))
    env = next(f for f in findings if f.category == "secret-management")
    assert env.severity == "high" and "SECRET_KEY" in env.explanation and "Kq8vT2pLm9" not in env.explanation


def test_app_factory_routes_and_string_literals_ignored(tmp_path: Path):
    r = parse_python("app/main.py", "from fastapi import FastAPI\ndef create_app():\n    app = FastAPI()\n    @app.get('/api/health')\n    def health():\n        return {}\n    return app\n")
    assert [(x.method, x.path, x.handler) for x in r.routes] == [("GET", "/api/health", "health")]
    (tmp_path / "rules.py").write_text('DOC = "configure allow_origins=[\'*\'] carefully"\nos.system(cmd)\n')
    files = [FileRecord(path="rules.py", size=10, language="Python", category=FileCategory.SOURCE)]
    findings, _ = scan_security(ScanContext(root=tmp_path, files=files, modules=[], routes=[], dependencies=[], env_vars=[], technologies=[]))
    assert {f.category for f in findings} == {"command-injection"}
